#!/usr/bin/env python3
"""Build one PDF mode with independent auxiliary files and safe overrides."""
import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("guidance", "submission"))
    args = parser.parse_args()
    funding = os.environ.get("FUNDING") or "standard"
    limit = os.environ.get("PAGE_LIMIT", "")
    if funding not in ("standard", "lump-sum"):
        parser.error("FUNDING must be standard or lump-sum")
    if limit and (not limit.isascii() or not limit.isdecimal() or int(limit) < 1):
        parser.error("PAGE_LIMIT must be a positive integer")
    if shutil.which("latexmk") is None:
        parser.error("latexmk is required; see README.md for installation")
    if not (ROOT / "part-b2.tex").is_file():
        parser.error("part-b2.tex is missing")
    directory = ROOT / "build" / args.mode
    directory.mkdir(parents=True, exist_ok=True)
    content = "% Generated by scripts/build.py; edit metadata.tex instead.\n"
    content += "\\def\\HEGuidance{" + ("1" if args.mode == "guidance" else "0") + "}\n"
    content += "\\def\\HEFunding{" + funding + "}\n"
    if limit:
        content += "\\def\\HEPageLimit{" + str(int(limit)) + "}\n"
    content += "\\input{part-b2.tex}\n"
    driver = directory / "driver.tex"
    if not driver.exists() or driver.read_text(encoding="utf-8") != content:
        driver.write_text(content, encoding="utf-8")
    job = "part-b2-guidance" if args.mode == "guidance" else "part-b2"
    command = ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error",
               "-file-line-error", f"-outdir=build/{args.mode}", f"-jobname={job}",
               f"build/{args.mode}/driver.tex"]
    try:
        return subprocess.run(command, cwd=ROOT, check=False).returncode
    except OSError as error:
        print(f"Build error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
